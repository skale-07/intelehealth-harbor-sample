def render() -> dict[str, bytes]:
    protocol = load_protocol(PROTOCOL_SRC)
    protocol_bytes = PROTOCOL_SRC.read_bytes()
    grader = {name: (SHARED / name).read_bytes() for name in GRADER_FILES}
    files: dict[str, bytes] = {}
    files["README.md"] = _dataset_readme().encode("utf-8")
    files["manifest.json"] = dump_json(manifest_payload()).encode("utf-8")
    files["GENERATED.txt"] = (GENERATED + "\n").encode("utf-8")

    for case in iter_cases():
        validate_case(case, protocol)
        prefix = case["case_id"]
        kind = case["task_kind"]
        files[f"{prefix}/instruction.md"] = _instruction(kind).encode("utf-8")
        files[f"{prefix}/task.toml"] = _task_toml(case).encode("utf-8")
        files[f"{prefix}/environment/Dockerfile"] = _env_dockerfile(kind).encode("utf-8")
        files[f"{prefix}/environment/case/patient_state.json"] = dump_json(
            case["patient_state"]
        ).encode("utf-8")
        files[f"{prefix}/environment/case/protocol.json"] = protocol_bytes
        files[f"{prefix}/tests/Dockerfile"] = _tests_dockerfile(kind).encode("utf-8")
        files[f"{prefix}/tests/test.sh"] = _test_sh().encode("utf-8")
        files[f"{prefix}/tests/test_proposal.py"] = _test_proposal_py(kind).encode("utf-8")
        files[f"{prefix}/tests/demo_rules.json"] = dump_json(DEMO_RULES).encode("utf-8")
        files[f"{prefix}/tests/case/patient_state.json"] = dump_json(
            case["patient_state"]
        ).encode("utf-8")
        files[f"{prefix}/tests/case/protocol.json"] = protocol_bytes
        files[f"{prefix}/tests/case/meta.json"] = dump_json(
            {
                "case_id": case["case_id"],
                "task_kind": case["task_kind"],
                "suite": case["suite"],
                "pair_id": case["pair_id"],
                "variant": case["variant"],
                "policy_id": case["policy_id"],
                "report_slice": case["report_slice"],
            }
        ).encode("utf-8")
        if case["oracle"] is not None:
            files[f"{prefix}/tests/case/oracle.json"] = dump_json(case["oracle"]).encode("utf-8")
        if case["patient_script"] is not None:
            files[f"{prefix}/tests/case/patient_script.json"] = dump_json(
                case["patient_script"]
            ).encode("utf-8")
        for name, payload in grader.items():
            files[f"{prefix}/tests/{name}"] = payload
        files[f"{prefix}/solution/solve.sh"] = (
            _solve_rollout() if kind == "rollout_intake" else _solve_oneshot(case["oracle"])
        ).encode("utf-8")
        if kind == "rollout_intake":
            files[f"{prefix}/environment/agent.py"] = STUB_AGENT.encode("utf-8")
            files[f"{prefix}/solution/agent.py"] = _policy_agent(
                case["close_disposition"]
            ).encode("utf-8")
    return files


def write_files(files: dict[str, bytes], dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    for rel, payload in files.items():
        path = dest / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(payload)
    for rel in existing_files(dest):
        if rel not in files:
            (dest / rel).unlink()


def existing_files(dest: Path) -> dict[str, bytes]:
    if not dest.is_dir():
        return {}
    out: dict[str, bytes] = {}
    for path in dest.rglob("*"):
        if path.is_file():
            rel = path.relative_to(dest).as_posix()
            out[rel] = path.read_bytes()
    return out


def diff_files(expected: dict[str, bytes], actual: dict[str, bytes]) -> list[str]:
    msgs: list[str] = []
    for rel in sorted(set(expected) | set(actual)):
        if rel not in actual:
            msgs.append(f"missing {rel}")
        elif rel not in expected:
            msgs.append(f"extra {rel}")
        elif expected[rel] != actual[rel]:
            msgs.append(f"mismatch {rel}")
    return msgs


def build() -> None:
    files = render()
    write_files(files, V3_ROOT)
    (SHARED / "v3_manifest.json").write_bytes(files["manifest.json"])


def check() -> int:
    expected = render()
    actual = existing_files(V3_ROOT)
    msgs = diff_files(expected, actual)
    shared_manifest = SHARED / "v3_manifest.json"
    if not shared_manifest.is_file() or shared_manifest.read_bytes() != expected["manifest.json"]:
        msgs.append("mismatch shared/v3_manifest.json")
    if msgs:
        print("V3 task tree is stale or dirty:")
        for msg in msgs:
            print(f"  {msg}")
        return 1
    print(f"V3 tasks match generator ({len(expected)} files)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="compare disk to generator; do not write")
    args = parser.parse_args(argv)
    if args.check:
        return check()
    build()
    print(f"wrote {V3_ROOT}")
    return check()


if __name__ == "__main__":
    raise SystemExit(main())
