def _env_dockerfile(kind: str) -> str:
    extra = ""
    if kind == "rollout_intake":
        extra = "COPY agent.py /app/agent.py\n"
    return (
        f"# {GENERATED}\n"
        "FROM python:3.12-slim-bookworm\n"
        "WORKDIR /app\n"
        "RUN mkdir -p /app/case /logs/agent /logs/verifier\n"
        "COPY case/patient_state.json /app/case/patient_state.json\n"
        "COPY case/protocol.json /app/case/protocol.json\n"
        f"{extra}"
    )


